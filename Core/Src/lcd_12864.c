/* Function */
// Initiate lcd
void Init_12864(void){
	//set up the lcd function with the spi and gpio callback
	u8g2_Setup_st7920_s_128x64_f(&u8g2, U8G2_R2, u8x8_spi, u8g2_gpio_and_delay);
	//Init display and set it to power down mode
	u8g2_InitDisplay(&u8g2);
	//set power mode to 0 to init and displaying
	u8g2_SetPowerSave(&u8g2, 0);
	//Clear display buffer, u8g2_sendBuffer do the same thing
	u8g2_ClearBuffer(&u8g2);
	u8g2_ClearDisplay(&u8g2);
}
